/**
 * `PullRequest` — reads the journal after [cursor].
 *
 * [cursor] is required-and-nullable and therefore has no default: null on an initial sync means
 * "from the beginning", and an absent key would be a third state. [limit] is `.optional()` in
 * Zod and not `.nullable()`, so it must be *omitted* when unset — which is what a default plus
 * [SyncJson]'s `encodeDefaults = false` produces.
 *
 * [supportedSchemaVersions] is required, and it is what turns PRD 12.4 into a server-enforced
 * invariant rather than a client-side hope: the client states what it can apply, and a server
 * holding anything newer answers [PullUpgradeRequiredDto] instead of a page the client would
 * half-apply.
 */
@Serializable
data class PullRequestDto(
    val cursor: String?,
    val limit: Int? = null,
    val supportedSchemaVersions: Map<String, List<Int>>,
)

/**
 * `PullResponse` — a sealed hierarchy, and the single most load-bearing shape in this file.
 *
 * A flat class with a nullable `nextCursor` would compile, parse both branches and be wrong:
 * the engine could read a cursor on a response that protocol-wise has none, and advance past
 * data it cannot apply. [PullUpgradeRequiredDto] genuinely has no `nextCursor` property, so
 * that mistake is not a bug to be caught in review — it does not typecheck.
 *
 * Both outcomes are HTTP 200 with a discriminated body, matching push: a rejected mutation and
 * an unapplicable payload are business results, not transport failures, and a non-2xx would
 * make a client throw before the body, and its actionable [MueErrorDto], were ever parsed.
 */
@OptIn(ExperimentalSerializationApi::class)
@Serializable
@JsonClassDiscriminator("status")
sealed interface PullResponseDto {
    val serverTime: String

    /**
     * FR-SYNC-008: the age of the last Android sync the server knows about, so no reader infers
     * a freshness guarantee the server cannot give. Null when no device has ever synchronised.
     */
    val lastAndroidSyncAt: String?
}

